"""Data mixing optimization for training.

Implements approaches to find optimal data source proportions:

1. Presets: Expert-defined ratios based on domain knowledge
2. Inverse-Loss: Track per-source validation loss, increase weight of high-loss sources
3. Grid Search: Try N mixing ratios with small proxy model, pick best (stub)

For a small project, approach 1 (presets) or 2 (inverse-loss reweighting) is most
practical. Grid search requires training infrastructure and is provided as a stub.

Think of this like load balancer weights in a microservice architecture:
you want to route more traffic (training data) to the services (domains)
that are underperforming, not the ones already doing fine.

Usage:
    from cola_coder.data.mixing import MixingConfig, MIXING_PRESETS

    # Use a preset
    config = MixingConfig.from_preset("typescript_focused")
    print(config.sources)
    # {"typescript": 0.50, "javascript": 0.25, "python": 0.15, "other": 0.10}

    # Use inverse-loss reweighting
    optimizer = MixingOptimizer()
    config = optimizer.suggest_proportions({
        "typescript": 2.8,  # high loss = model struggles here
        "javascript": 2.1,
        "python": 1.9,      # low loss = model is already decent
    })
    # typescript gets higher weight since it has the highest loss
"""

from __future__ import annotations

import logging
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def write_weighted_data_sources(
    ratios: dict[str, float],
    out_path: str | Path,
    base_path: str | Path = "configs/data_sources.yaml",
) -> Path:
    """Write a derived data_sources.yaml with per-source weights from `ratios`.

    `scripts/collect_data.py` reads `sources.{code,text,math}.weight` to decide
    the collection mix. This builds a derived config from `base_path` (preserving
    each source's dataset/languages/length settings) with the weights overridden,
    so the "Prepare Mixed Data" menu's ratio choice actually controls the mix.
    A source with weight 0 is disabled so collect_data skips it entirely.

    Args:
        ratios: e.g. {"code": 0.7, "text": 0.15, "math": 0.15}.
        out_path: Where to write the derived config.
        base_path: Base data_sources.yaml to copy non-weight fields from.

    Returns:
        The path the derived config was written to.
    """
    import yaml

    base = yaml.safe_load(Path(base_path).read_text(encoding="utf-8")) or {}
    sources = base.setdefault("sources", {})
    for name, weight in ratios.items():
        src = sources.setdefault(name, {})
        src["weight"] = float(weight)
        src["enabled"] = float(weight) > 0.0

    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Auto-generated by the Prepare Mixed Data menu — edits will be "
        "overwritten.\n" + yaml.safe_dump(base, sort_keys=False),
        encoding="utf-8",
    )
    return out


# ---------------------------------------------------------------------------
# MixingConfig — describes a set of source proportions
# ---------------------------------------------------------------------------


@dataclass
class MixingConfig:
    """Define mixing proportions for data sources.

    Like a TypeScript Record<string, number> — maps source names to their
    weight in the training mix. Weights are relative and get normalized
    to sum to 1.0 before use.

    Attributes:
        sources: Mapping of source name to weight.
            e.g., {"typescript": 0.5, "javascript": 0.2, "python": 0.3}
    """

    sources: dict[str, float]

    def __post_init__(self):
        if not self.sources:
            raise ValueError("MixingConfig requires at least one source")
        for name, weight in self.sources.items():
            if weight < 0:
                raise ValueError(
                    f"Weight for {name!r} must be non-negative, got {weight}"
                )
        if sum(self.sources.values()) <= 0:
            raise ValueError("Weights must sum to a positive number")

    @classmethod
    def from_preset(cls, preset: str) -> MixingConfig:
        """Load a preset mixing config by name.

        Available presets:
            - "typescript_focused": 50% TS, 25% JS, 15% Python, 10% other
            - "balanced_code": Distributed across 6 languages
            - "quality_tiers": Weight by data quality level
            - "equal": Equal weights for all languages in the preset

        Raises:
            KeyError: If the preset name is not found.
        """
        if preset not in MIXING_PRESETS:
            available = ", ".join(sorted(MIXING_PRESETS.keys()))
            raise KeyError(
                f"Unknown mixing preset {preset!r}. "
                f"Available presets: {available}"
            )
        return MIXING_PRESETS[preset]

    def normalize(self) -> MixingConfig:
        """Return a new MixingConfig with weights normalized to sum to 1.0.

        Like Array.map(x => x / total) — rescales all weights proportionally
        so they sum to exactly 1.0.
        """
        total = sum(self.sources.values())
        if total <= 0:
            raise ValueError("Cannot normalize: weights sum to zero or negative")
        normalized = {k: v / total for k, v in self.sources.items()}
        return MixingConfig(sources=normalized)

    def is_normalized(self, tol: float = 1e-6) -> bool:
        """Check if weights already sum to ~1.0."""
        return abs(sum(self.sources.values()) - 1.0) < tol

    def to_weight_list(self, source_names: list[str]) -> list[float]:
        """Convert to an ordered list of weights matching the given source names.

        Sources not present in this config get weight 0.0.
        Useful for passing to DatasetCombiner or MixedSource which expect lists.

        Args:
            source_names: Ordered list of source names.

        Returns:
            List of weights in the same order, normalized to sum to 1.0.
        """
        raw = [self.sources.get(name, 0.0) for name in source_names]
        total = sum(raw)
        if total <= 0:
            # None of the requested sources are in this config
            # Fall back to equal weights
            return [1.0 / len(source_names)] * len(source_names)
        return [w / total for w in raw]

    def describe(self) -> str:
        """Human-readable description of the mixing proportions."""
        normalized = self.normalize()
        parts = []
        for name, weight in sorted(
            normalized.sources.items(), key=lambda x: -x[1]
        ):
            parts.append(f"{name}: {weight:.0%}")
        return ", ".join(parts)

    def to_dict(self) -> dict[str, Any]:
        """Serialize to a plain dict (for YAML/JSON config files)."""
        return {"sources": dict(self.sources)}

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> MixingConfig:
        """Deserialize from a plain dict."""
        return cls(sources=data["sources"])


