# ---------------------------------------------------------------------------
# PerSourceTracker — track validation loss per data source
# ---------------------------------------------------------------------------


class PerSourceTracker:
    """Track validation loss per data source during training.

    After each validation step, records the loss broken down by which source
    each validation example came from. This enables dynamic reweighting
    during training.

    Like a per-route error rate tracker in a web app — you want to know
    which route is failing the most so you can prioritize fixing it.

    Usage:
        tracker = PerSourceTracker()

        # During validation
        for batch in val_loader:
            loss = model(batch)
            source = batch.metadata["source"]
            tracker.record(source, loss.item())

        # After validation
        weights = tracker.get_weights(method="inverse_loss")
        # {"typescript": 0.40, "python": 0.35, "javascript": 0.25}
    """

    def __init__(self):
        self.source_losses: dict[str, list[float]] = {}

    def record(self, source: str, loss: float) -> None:
        """Record a validation loss for a given source.

        Args:
            source: Name of the data source (e.g., "typescript", "python").
            loss: The loss value for this example/batch.
        """
        if source not in self.source_losses:
            self.source_losses[source] = []
        self.source_losses[source].append(loss)

    def mean_losses(self) -> dict[str, float]:
        """Compute mean loss per source.

        Returns:
            Dict mapping source name to its mean validation loss.
        """
        return {
            source: sum(losses) / len(losses)
            for source, losses in self.source_losses.items()
            if losses
        }

    def get_weights(self, method: str = "inverse_loss") -> dict[str, float]:
        """Compute mixing weights based on tracked losses.

        Args:
            method: Weighting method. One of:
                - "inverse_loss": Higher loss sources get proportionally more
                  weight. weight_i = loss_i / sum(losses). Simple and effective.
                - "softmax": Use softmax of losses for smoother weighting.
                  Prevents extreme weights when one source has much higher loss.
                - "equal": Ignore losses, return equal weights.

        Returns:
            Dict mapping source name to its computed weight (sums to 1.0).

        Raises:
            ValueError: If no losses have been recorded or unknown method.
        """
        means = self.mean_losses()
        if not means:
            raise ValueError("No losses recorded yet")

        if method == "equal":
            n = len(means)
            return {source: 1.0 / n for source in means}

        elif method == "inverse_loss":
            # Higher loss = higher weight (model needs more exposure)
            total = sum(means.values())
            if total <= 0:
                return {source: 1.0 / len(means) for source in means}
            return {source: loss / total for source, loss in means.items()}

        elif method == "softmax":
            # Softmax of losses — smoother than raw proportional
            # Subtract max for numerical stability
            max_loss = max(means.values())
            exp_vals = {
                source: math.exp(loss - max_loss)
                for source, loss in means.items()
            }
            total = sum(exp_vals.values())
            return {source: val / total for source, val in exp_vals.items()}

        else:
            raise ValueError(
                f"Unknown weighting method {method!r}. "
                f"Use 'inverse_loss', 'softmax', or 'equal'."
            )

    def reset(self) -> None:
        """Clear all recorded losses."""
        self.source_losses.clear()

    def summary(self) -> str:
        """Human-readable summary of per-source losses and suggested weights."""
        means = self.mean_losses()
        if not means:
            return "No losses recorded yet."

        lines = ["Per-source validation losses:"]
        for source, loss in sorted(means.items(), key=lambda x: -x[1]):
            count = len(self.source_losses[source])
            lines.append(f"  {source}: {loss:.4f} (n={count})")

        weights = self.get_weights(method="inverse_loss")
        lines.append("\nSuggested weights (inverse_loss):")
        for source, weight in sorted(weights.items(), key=lambda x: -x[1]):
            lines.append(f"  {source}: {weight:.2%}")

        return "\n".join(lines)


# ---------------------------------------------------------------------------
# MixingOptimizer — find optimal mixing proportions
# ---------------------------------------------------------------------------


class MixingOptimizer:
    """Find optimal data mixing proportions.

    Two approaches implemented:

    1. suggest_proportions(): Given per-source validation losses, suggest
       new proportions using inverse-loss reweighting (simplified DoReMi).
       Cheap and effective for iterative refinement.

    2. grid_search(): Full grid search with proxy training. Define candidate
       ratios, train a tiny model for each, pick the best. More principled
       but expensive. Currently a stub that returns the preset ratios.

    Think of it like A/B testing for data proportions:
    - suggest_proportions = quick heuristic (like using error rates to route traffic)
    - grid_search = full experiment (like running actual A/B tests)

    Args:
        eval_steps: Number of training steps per candidate in grid search.
        candidates: Number of candidate ratios to try in grid search.
    """

    def __init__(self, eval_steps: int = 500, candidates: int = 10):
        self.eval_steps = eval_steps
        self.candidates = candidates

    def suggest_proportions(
        self,
        source_losses: dict[str, float],
        method: str = "inverse_loss",
        temperature: float = 1.0,
    ) -> MixingConfig:
        """Suggest proportions based on per-source validation loss.

        Higher loss sources get more weight (model needs more exposure).
        This is a simplified DoReMi approach without the reference model.

        Args:
            source_losses: Dict mapping source name to its validation loss.
                e.g., {"typescript": 2.8, "javascript": 2.1, "python": 1.9}
            method: Weighting method ("inverse_loss" or "softmax").
            temperature: Temperature for softmax method. Higher = more uniform.
                Ignored for inverse_loss method.

        Returns:
            MixingConfig with suggested proportions (normalized to sum to 1.0).
        """
        if not source_losses:
            raise ValueError("source_losses must not be empty")

        if method == "inverse_loss":
            total = sum(source_losses.values())
            if total <= 0:
                n = len(source_losses)
                weights = {s: 1.0 / n for s in source_losses}
            else:
                weights = {s: loss / total for s, loss in source_losses.items()}

        elif method == "softmax":
            # Apply temperature scaling then softmax
            max_loss = max(source_losses.values())
            exp_vals = {
                s: math.exp((loss - max_loss) / temperature)
                for s, loss in source_losses.items()
            }
            total = sum(exp_vals.values())
            weights = {s: v / total for s, v in exp_vals.items()}

        else:
            raise ValueError(f"Unknown method {method!r}")

        logger.info(
            "Suggested mixing proportions (%s): %s",
            method,
            {s: f"{w:.2%}" for s, w in weights.items()},
        )

        return MixingConfig(sources=weights)

    def grid_search(
        self,
        sources: dict[str, str],
        eval_data: str,
    ) -> MixingConfig:
        """Full grid search with proxy training.

        This is a stub — implementing it requires the full training loop.
        In a real implementation, this would:
        1. Generate `self.candidates` candidate mixing ratios
        2. For each ratio, create a DatasetCombiner with those weights
        3. Train a tiny proxy model for `self.eval_steps` steps
        4. Measure validation loss on eval_data
        5. Return the ratio with the lowest validation loss

        Args:
            sources: Dict mapping source name to path to data directory.
                e.g., {"typescript": "data/processed/train_ts.npy"}
            eval_data: Path to evaluation dataset.

        Returns:
            MixingConfig with the best proportions found.

        Raises:
            NotImplementedError: Always (this is a stub).
        """
        raise NotImplementedError(
            "Grid search requires training infrastructure. "
            "Use suggest_proportions() with per-source validation losses "
            "for a lightweight alternative, or use a preset from MIXING_PRESETS."
        )

    def generate_candidates(
        self,
        source_names: list[str],
        n: int | None = None,
    ) -> list[MixingConfig]:
        """Generate candidate mixing ratios for grid search.

        Creates a spread of mixing ratios using a simplex grid. Useful if
        you want to implement your own grid search loop.

        For 2 sources: generates n points along [0,1] for the first source.
        For 3+ sources: generates a coarse grid on the probability simplex.

        Args:
            source_names: List of source names.
            n: Number of candidates to generate. Defaults to self.candidates.

        Returns:
            List of MixingConfig objects, each representing one candidate ratio.
        """
        n = n or self.candidates
        k = len(source_names)

        if k == 0:
            raise ValueError("Need at least one source")

        if k == 1:
            return [MixingConfig(sources={source_names[0]: 1.0})]

        if k == 2:
            # Simple linear sweep
            configs = []
            for i in range(n):
                w1 = (i + 1) / (n + 1)  # Avoid 0.0 and 1.0 extremes
                w2 = 1.0 - w1
                configs.append(
                    MixingConfig(
                        sources={source_names[0]: w1, source_names[1]: w2}
                    )
                )
            return configs

        # For 3+ sources: generate random points on the simplex
        # (uniform grid on the simplex is combinatorially expensive)
        import random

        rng = random.Random(42)
        configs = []
        for _ in range(n):
            # Dirichlet-like: generate k exponentials, normalize
            raw = [rng.expovariate(1.0) for _ in range(k)]
            total = sum(raw)
            weights = {
                source_names[i]: raw[i] / total for i in range(k)
            }
            configs.append(MixingConfig(sources=weights))

        return configs
