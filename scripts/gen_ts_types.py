def _is_union(origin: object) -> bool:
    return origin is Union or origin is _types.UnionType


def _is_json_value(annotation: object) -> bool:
    """True if the annotation is exactly the shared ``schemas.JsonValue`` alias."""
    return annotation is schemas.JsonValue


def _ts_for_annotation(annotation: object) -> str:
    """Map a Python type annotation to its TypeScript expression."""
    if _is_json_value(annotation):
        return "JsonValue"

    if annotation is None or annotation is type(None):
        return "null"
    if annotation is str:
        return "string"
    if annotation is bool:
        return "boolean"
    if annotation is int or annotation is float:
        return "number"

    origin = get_origin(annotation)

    if origin is typing.Literal:
        return _ts_for_literal(get_args(annotation))

    if _is_union(origin):
        return _ts_for_union(get_args(annotation))

    if origin in (list, typing.List):  # noqa: UP006 - explicit for clarity
        (inner,) = get_args(annotation)
        return f"{_ts_for_element(inner)}[]"

    if origin in (dict, typing.Dict):  # noqa: UP006
        _key, value = get_args(annotation)
        return f"Record<string, {_ts_for_annotation(value)}>"

    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return _interface_name(annotation)

    raise TypeError(f"Unsupported annotation for TS generation: {annotation!r}")


def _ts_for_element(annotation: object) -> str:
    """TS for an array/element position; parenthesize unions so ``X[]`` binds."""
    rendered = _ts_for_annotation(annotation)
    origin = get_origin(annotation)
    if _is_union(origin) and not _is_json_value(annotation):
        return f"({rendered})"
    return rendered


def _ts_for_literal(args: tuple[object, ...]) -> str:
    parts: list[str] = []
    for arg in args:
        if isinstance(arg, bool):
            parts.append("true" if arg else "false")
        elif isinstance(arg, str):
            parts.append(f"'{arg}'")
        elif isinstance(arg, (int, float)):
            parts.append(str(arg))
        else:
            raise TypeError(f"Unsupported Literal member: {arg!r}")
    return " | ".join(parts)


def _ts_for_union(args: tuple[object, ...]) -> str:
    parts: list[str] = []
    for arg in args:
        rendered = _ts_for_annotation(arg)
        if rendered not in parts:
            parts.append(rendered)
    return " | ".join(parts)


def _interface_name(model: type[BaseModel]) -> str:
    """The TS interface name for a model (ErrorResponse → ApiError)."""
    if model is schemas.ErrorResponse:
        return "ApiError"
    return model.__name__


def _field_is_optional_marker(info: FieldInfo) -> bool:
    """True if the TS field should be marked ``name?:`` (has a default → may be
    absent in the response).
    """
    return not info.is_required()


def _emit_interface(model: type[BaseModel]) -> str:
    lines = [f"export interface {model.__name__} {{"]
    for field_name, info in model.model_fields.items():
        ts_type = _ts_for_annotation(info.annotation)
        optional = "?" if _field_is_optional_marker(info) else ""
        lines.append(f"  {field_name}{optional}: {ts_type};")
    lines.append("}")
    return "\n".join(lines)


def build_ts() -> str:
    """Build the full deterministic types.gen.ts content as a string."""
    blocks: list[str] = [_HEADER.rstrip("\n"), "", _JSON_VALUE_BLOCK.rstrip("\n"), ""]

    for name in _MODEL_ORDER:
        model = getattr(schemas, name)
        blocks.append(_emit_interface(model))
        blocks.append("")

    # ApiError (from ErrorResponse) + type guard, mirroring types.ts.
    blocks.append(_emit_interface(schemas.ErrorResponse).replace(
        "export interface ErrorResponse {", "export interface ApiError {"
    ))
    blocks.append("")
    blocks.append(
        "export function isApiError<T>(v: T | ApiError): v is ApiError {\n"
        "  return (\n"
        "    typeof v === 'object' &&\n"
        "    v !== null &&\n"
        "    !Array.isArray(v) &&\n"
        "    typeof (v as ApiError).error === 'string'\n"
        "  );\n"
        "}"
    )
    blocks.append("")

    for name in _OR_ERROR:
        blocks.append(f"export type {name}OrError = {name} | ApiError;")
    blocks.append("")

    return "\n".join(blocks)


def main() -> int:
    content = build_ts()
    _OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    _OUTPUT_PATH.write_text(content, encoding="utf-8", newline="\n")
    n_interfaces = len(_MODEL_ORDER) + 1  # + ApiError
    cli.success(f"Wrote {_OUTPUT_PATH} ({n_interfaces} interfaces, "
                f"{len(_OR_ERROR)} OrError aliases).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
