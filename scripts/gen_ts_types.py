"""Generate ``webui/src/types.gen.ts`` from the Pydantic models in
``src/cola_coder/ui/schemas.py`` (the single source of truth).

Introspects every UI ``BaseModel`` via ``model_fields`` + ``typing`` and emits
exact 1:1 TypeScript interfaces. Output is deterministic (fixed model order,
declared field order) so ``tests/test_ui_types_generated.py`` can byte-compare
against the committed file as a drift guard.

NEVER hand-edit types.gen.ts — edit schemas.py and run this script.

Usage:
    .venv/Scripts/python.exe scripts/gen_ts_types.py
"""

